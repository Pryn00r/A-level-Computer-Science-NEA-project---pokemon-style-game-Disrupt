# language code -> name shown in the settings menu
LANGUAGES = {'en': 'English', 'it': 'Italiano', 'es': 'Español'}

# the language currently in use (changed by set_language)
current_language = 'en'

# Changes the current language. Lookup check: an unknown code falls back to English.
def set_language(language):
	global current_language
	current_language = language if language in LANGUAGES else 'en'

# Returns the text for a key in the current language, filling in any {values}. Missing translations
# fall back to English so a screen is never blank. Used for every string on every menu screen.
def t(key, **values):
	# missing translations fall back to English so that a screen is never left blank
	text = STRINGS[current_language].get(key, STRINGS['en'].get(key, key))
	return text.format(**values) if values else text

# Iteration 18: names shown on screen for attacks and stats (the game data keeps the English keys).
def attack_name(attack):
	return t(f'attack_{attack}')

def stat_name(stat):
	return t(f'stat_{stat}')

# Returns a help/policy document (list of (heading, body) pairs) in the current language.
def get_document(key):
	return DOCUMENTS[current_language].get(key, DOCUMENTS['en'][key])


