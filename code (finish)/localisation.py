# Iteration 32: a list of short lines saying what a move does
def move_effects(data):
	lines = []
	if data.get('kind') == 'heal':
		lines.append(t('fx_heal', percent = round(data.get('heal', 0) * 100)))
	if data.get('status'):
		status, chance = data['status']
		lines.append(t('fx_status', chance = round(chance * 100), status = t(f'fx_s_{status}')))
	if data.get('stat'):
		stat, change = data['stat']
		if data['target'] == 'player':
			lines.append(t('fx_stat_up', stat = stat_name(stat)))
		else:
			chance = 1 if data.get('kind') == 'status' else data.get('stat_chance', 1)
			lines.append(t('fx_stat_down', chance = round(chance * 100), stat = stat_name(stat)))
	if data.get('self_status'):
		lines.append(t('fx_self', chance = round(data['self_status'][1] * 100)))
	if data.get('charge'):
		lines.append(t('fx_charge'))
	if data.get('priority', 0) > 0:
		lines.append(t('fx_fast'))
	elif data.get('priority', 0) < 0:
		lines.append(t('fx_slow'))
	return lines or [t('fx_plain')]

